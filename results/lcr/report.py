"""Write results/lcr/REPORT.md from the stored results in results/lcr/data (no GPU, no dataset needed).

    python results/lcr/report.py
"""
import json
import pathlib

import numpy as np

HERE = pathlib.Path(__file__).parent
D = HERE / "data"
BINS = ("all", "0-30", "30-50", "50-100", "100-200", "50-200")
FAR = ("50-200", "100-200")
CONDS = ("highway", "urban", "night", "rain")
MODELS = {
    "L": "SECOND alone (LiDAR)",
    "LC": "R0+T2+K40: camera CLOCs (SECOND + Cascade R-CNN)",
    "LRd": "R0+T2+RP: radar CLOCs (SECOND + D2's boxes as the pairs)",
    "B": "fixed blend of L, LC and LRd logits (two CLOCs networks; not executable on master)",
    "LCR": "R0+T2+K40+RC: **one CLOCs network over SECOND, Cascade R-CNN and D2** (main model)",
    "LCR-D": "R0+T2+K40+RC+DF: LCR with far camera cells hidden half the time in training",
}


def load(name):
    return json.load(open(D / name))


def runs(*parts):
    """Per-seed results of one model, merged across files: [(file, key)] -> {seed: {split: metrics}}."""
    out = {}
    for f, key in parts:
        for r in load(f)[key]["runs"]:
            out.setdefault(r["seed"], {}).update({s: r[s] for s in ("select", "val") if s in r})
    assert sorted(out) == [1, 2, 3, 4, 5, 6], (parts, sorted(out))
    return out


def second():
    d = load("aimotive_second.json")
    return {0: {s: d[s] for s in ("select", "val")}}


SEEDS = {
    "L": second(),
    "LC": runs(("final_r0_s123.json", "R0+T2+K40"), ("final_s456.json", "R0+T2+K40")),
    "LRd": runs(("experts_rp.json", "R0+T2+RP"), ("val_experts_rp.json", "R0+T2+RP")),
    "B": runs(("blend.json", "B(R0+T2+RP)"), ("blend_val.json", "B(R0+T2+RP)")),
    "LCR": runs(("lcr.json", "R0+T2+K40+RC"), ("lcr_val.json", "R0+T2+K40+RC")),
    "LCR-D": runs(("lcrd.json", "R0+T2+K40+RC+DF"), ("lcrd_val.json", "R0+T2+K40+RC+DF")),
}


def apcd(model, split, group="overall", b="50-200"):
    return np.array([r[split][group][b]["APCD"] for _, r in sorted(SEEDS[model].items())])


def cell(x):
    return f"{x.mean():.4f}" if len(x) == 1 else f"{x.mean():.4f} ± {x.std(ddof=1):.4f}"


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(r) + " |" for r in rows]


def paired(a, b, split, bn):
    if len(SEEDS[b]) == 1:
        d = apcd(a, split, b=bn) - apcd(b, split, b=bn)[0]
    else:
        d = apcd(a, split, b=bn) - apcd(b, split, b=bn)
    return f"{d.mean():+.4f} ({int((d > 0).sum())}/6)"


def boot(f, comp, split):
    c = load(f.format(split=split))["comparisons"][comp]
    return {b: f"{v['diff']:+.4f} [{v['lo']:+.4f}, {v['hi']:+.4f}]" for b, v in c.items()}


def main():
    out = ["# LCR: results", "",
           "Generated by `python results/lcr/report.py` from the files in `data/` (copied unchanged from the project",
           "record on the `thesis` branch, `results/next_round/`). APCD is centre-distance AP for cars, averaged over the",
           "0.5, 1, 2 and 4 m thresholds. Fusion models: mean ± SD over seeds 1–6, all trained on `fit`.",
           "`select` (24 scenes, 3,409 frames) chose every setting; val (25 scenes, 5,181 frames) was scored once per model.", ""]
    out += ["## Models", ""] + table(["Label", "Model"], [[k, v] for k, v in MODELS.items()]) + [""]

    out += ["## Detectors alone", "", "**SECOND** (APCD) and **D2** (radar-only PointPillars, APCD):", ""]
    sec, d2 = load("aimotive_second.json"), load("radar_detector_d2.json")
    rows = [[f"SECOND, {s}"] + [f"{sec[s]['overall'][b]['APCD']:.4f}" for b in BINS] for s in ("select", "val")]
    rows += [[f"D2, {s}"] + [f"{d2[s]['overall'][b]['APCD']:.4f}" for b in BINS] for s in d2]
    out += table(["Detector, split"] + list(BINS), rows) + [""]
    cas = load("aimotive_cascade.json")
    out += ["**Cascade R-CNN**: share of cars with a 2D candidate of IoU ≥ 0.5 (recall@0.5):", ""]
    out += table(["Split"] + list(BINS), [[s] + [f"{cas[s]['overall']['recall'][b]['recall@0.5']:.3f}" for b in BINS]
                                          for s in ("select", "val")]) + [""]
    cl = load("clutter.json")
    out += [f"**Clutter classifier** (D2's seventh point feature): AUC {cl['auc_select']:.3f} on `select` "
            f"({cl['auc_select_far']:.3f} beyond 50 m).", ""]

    for split in ("select", "val"):
        out += [f"## All models on {'`select`' if split == 'select' else 'val'} (APCD by distance)", ""]
        out += table(["Model"] + list(BINS), [[m] + [cell(apcd(m, split, b=b)) for b in BINS] for m in SEEDS]) + [""]
        out += [f"By driving condition, 50–200 m / 100–200 m:", ""]
        out += table(["Model"] + list(CONDS), [[m] + [f"{apcd(m, split, c, '50-200').mean():.3f} / {apcd(m, split, c, '100-200').mean():.3f}"
                                                     for c in CONDS] for m in SEEDS]) + [""]

    out += ["## Seed-paired differences", "", "Mean difference, and the seeds (of 6) where the first model is higher.", ""]
    pairs = [("LCR", "L"), ("LCR", "LC"), ("LCR", "LRd"), ("LCR", "B"), ("LCR-D", "LCR"), ("LCR-D", "L"), ("LC", "L"), ("LRd", "L")]
    head = ["Comparison"] + [f"{s} {b}" for s in ("select", "val") for b in ("0-30", "30-50", "50-200", "100-200")]
    out += table(head, [[f"{a} − {b}"] + [paired(a, b, s, bn) for s in ("select", "val") for bn in ("0-30", "30-50", "50-200", "100-200")]
                        for a, b in pairs]) + [""]

    out += ["## Scene-bootstrap 95% intervals", "",
            "1,000 resamples of scenes with replacement; seeds averaged inside each resample; percentile intervals.", ""]
    comps = [("bootstrap_lcr_{split}.json", c) for c in ("LCR - L", "LCR - LC", "LCR - LRd", "LCR - B")]
    comps += [("bootstrap_lcrd_{split}.json", c) for c in ("LCRD - LCR", "LCRD - L")]
    comps += [("bootstrap_{split}.json", c) for c in ("LRd - L", "LC - L", "B - L")]
    for split in ("select", "val"):
        out += [f"**{'`select`' if split == 'select' else 'val'}**", ""]
        out += table(["Comparison", "50–100", "100–200", "50–200", "all"],
                     [[c.replace("LCRD", "LCR-D").replace(" - ", " − ")] + [boot(f, c, split)[b] for b in ("50-100", "100-200", "50-200", "all")]
                      for f, c in comps]) + [""]

    w = np.array([[r["select_weights"]["highway|0-30"][k] for k in ("L", "LC", "LR")] for r in load("blend.json")["B(R0+T2+RP)"]["runs"]])
    out += ["## Pre-registered rules", "",
            f"- **B's weights** (trained on `fit`, the same for every candidate): L {w[:, 0].mean():.3f}, "
            f"LC {w[:, 1].mean():.3f}, LRd {w[:, 2].mean():.3f} (mean over seeds)."]
    for f, label in (("decision_lcr.json", "LCR vs B"), ("decision_lcrd.json", "LCR-D vs LCR")):
        d = load(f)
        out.append(f"- **{label}:** {d['rule']}. Result: **{d['final']}**.")
        for b, v in d.items():
            if isinstance(v, dict):
                out.append(f"  - {b} m: " + ", ".join(f"{k} {x:.4f}" if isinstance(x, float) else f"{k} {x}" for k, x in v.items()))
    out += ["- **LCR is the main model by the author's choice** (simpler: one CLOCs network), overriding the rule's B. "
            "This is recorded as a departure from the pre-registration (thesis branch, `results/next_round/DECISIONS.md` item 13).", ""]
    (HERE / "REPORT.md").write_text("\n".join(out) + "\n")
    print("wrote", HERE / "REPORT.md")


if __name__ == "__main__":
    main()
